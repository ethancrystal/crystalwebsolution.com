#!/usr/bin/env node
// PostToolUse hook: after a shell command that runs `next build` / `next dev`
// (directly or via `pnpm build` / `pnpm dev`), restore tsconfig.json when the
// only difference from HEAD is what Next.js generates: the `jsx` flip, array
// reformatting, and `.next/` include globs. Any other edit is left alone and
// reported, so an intentional tsconfig change is never discarded.
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import { join } from 'node:path';

const NEXT_RUN = /\b(next|pnpm(\s+run)?)\s+(build|dev)\b/;

function readStdin() {
  try {
    return JSON.parse(readFileSync(0, 'utf8'));
  } catch {
    return {};
  }
}

function normalize(config) {
  const copy = structuredClone(config);
  if (copy.compilerOptions) delete copy.compilerOptions.jsx;
  if (Array.isArray(copy.include)) {
    copy.include = copy.include.filter((glob) => !glob.startsWith('.next/'));
  }
  return JSON.stringify(copy);
}

const event = readStdin();
const command = event?.tool_input?.command ?? '';
if (!NEXT_RUN.test(command)) process.exit(0);

const root = process.env.CLAUDE_PROJECT_DIR || event.cwd || process.cwd();
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' });

try {
  if (git('status', '--porcelain', '--', 'tsconfig.json').trim() === '') process.exit(0);

  const head = JSON.parse(git('show', 'HEAD:tsconfig.json'));
  const current = JSON.parse(readFileSync(join(root, 'tsconfig.json'), 'utf8'));

  if (normalize(head) === normalize(current)) {
    git('checkout', '--', 'tsconfig.json');
    process.stdout.write('Reverted the tsconfig.json rewrite generated by Next.js.\n');
  } else {
    process.stderr.write('tsconfig.json has edits beyond the Next.js rewrite; left as is.\n');
  }
} catch (error) {
  process.stderr.write(`revert-generated-tsconfig: ${error.message}\n`);
}
process.exit(0);
